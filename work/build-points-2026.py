"""Extract only remaining 2026 travel periods, matching the 2027 room/category order."""
import datetime,hashlib,json,re
from pathlib import Path
import pdfplumber
ROOT=Path(__file__).resolve().parents[1]
CHARTS=ROOT/'work/charts-2026'
CUTOFF=datetime.date(2026,10,20)
base=json.loads((ROOT/'points-2027.json').read_text())
sources=json.loads((CHARTS/'sources.json').read_text())
# Entries correspond to chart rows in top-to-bottom order; past-only periods are empty.
standard=['','','12-01/12-23','','10-20/11-24,11-28/11-30','11-25/11-27','12-24/12-31']
specs={
'AULV':['11-10/11-23,11-29/12-17','10-20/11-09','','11-24/11-28,12-18/12-31'],
'HH':['12-01/12-17','11-01/11-30,12-18/12-31','10-20/10-31',''],
'GCAL-VGC':['','10-20/11-23,11-29/12-17','','11-24/11-28,12-18/12-31'],
'VERO':['10-20/11-24','11-28/12-23','11-25/11-27','','12-24/12-31'],
'VDH':['','','','10-20/11-23,11-28/12-17','','','11-24/11-27,12-18/12-31']}
resorts=[];pairs=0
for resort in base['resorts']:
 code=resort['id'];p=CHARTS/(code+'.pdf');width=len(resort['categories'])
 with pdfplumber.open(p) as pdf:text=pdf.pages[0].extract_text()
 rates=[];weekly=[]
 for line in text.splitlines():
  m=re.search(r'(SUN—THU|SUN—SAT|FRI—SAT)\s+([\d ]+)$',line)
  if m:rates.append(list(map(int,m[2].split())))
  m=re.search(r'WEEKLY\s+([\d ]+)$',line)
  if m:weekly.append(list(map(int,m[1].split())))
  elif width>1 and re.fullmatch(r'[\d ]+',line) and len(line.split())==width:weekly.append(list(map(int,line.split())))
 periods=specs.get(code,standard);allWeek=code=='AULV'
 assert len(rates)==len(periods)*(1 if allWeek else 2),(code,'rate rows',len(rates))
 assert len(weekly)==len(periods),(code,'weekly rows',len(weekly))
 output=[];coverage=set()
 for i,spec in enumerate(periods):
  wd=rates[i if allWeek else i*2];we=wd if allWeek else rates[i*2+1]
  assert len(wd)==len(we)==len(weekly[i])==width,(code,'width')
  assert [5*a+2*b for a,b in zip(wd,we)]==weekly[i],(code,'weekly check',i)
  if not spec:continue
  ranges=[];labels=[]
  for pair in spec.split(','):
   a,b=[datetime.date.fromisoformat('2026-'+v) for v in pair.split('/')]
   assert a>=CUTOFF
   ranges.append({'start':a.isoformat(),'end':b.isoformat()});labels.append(a.strftime('%b %-d')+' – '+b.strftime('%b %-d'))
   while a<=b:
    assert a.isoformat() not in coverage,(code,'overlap')
    coverage.add(a.isoformat());a+=datetime.timedelta(days=1)
  output.append({'id':'2026-'+str(i+1),'label':'2026 · '+'; '.join(labels),'ranges':ranges,'rates':[{'weekday':a,'weekend':b} for a,b in zip(wd,we)]})
  pairs+=width
 assert len(coverage)==73,(code,'coverage',len(coverage))
 resorts.append({'id':code,'source':sources[code],'sourceSha256':hashlib.sha256(p.read_bytes()).hexdigest(),'periods':output})
 print(code,len(output),'remaining periods;',len(coverage),'days; weekly totals match')
data={'year':2026,'startDate':CUTOFF.isoformat(),'endDate':'2026-12-31','retrieved':'2026-10-20','resorts':resorts}
(ROOT/'points-2026.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
(ROOT/'points-2026.js').write_text('/* Official Disney 2026 chart data, October 20 onward. Generated by work/build-points-2026.py. */\nwindow.DVC_POINTS_2026 = '+json.dumps(data,ensure_ascii=False)+';\n')
print('Validated',pairs,'remaining room/period pairs across all resorts')
